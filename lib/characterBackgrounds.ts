export function normalizeCharacterName(name: string): string {
  return name
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/** Returns the shipped scene background for a seeded character, when available. */
export function getCharacterBackground(name: string | null | undefined): string | null {
  if (!name) return null;
  return CHARACTER_BACKGROUNDS[normalizeCharacterName(name)] ?? null;
}
